#!/usr/bin/env node
// gen-i18n-keys.mjs
//
// Emits entry/src/main/ets/core/i18n/I18nKeys.ets from the key manifest that
// scripts/generate-i18n-resources.mjs writes. Split out so the resource
// generator stays a pure JSON/JSON5 producer.
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const here = path.dirname(url.fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const MANIFEST = path.join(root, '.scratch', 'foundation', 'i18n-keys.json');
const OUT = path.join(root, 'entry', 'src', 'main', 'ets', 'core', 'i18n', 'I18nKeys.ets');

