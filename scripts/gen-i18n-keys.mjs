export function generateKeysSource() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
  const rows = manifest.keys;
  const localCount = rows.filter((r) => r.origin === 'local').length;
  const L = licenseHeader();
  L.push('');
  L.push('/**');
  L.push(' * Localised string keys, mirroring the element string.json files.');
  L.push(' *');
  L.push(' * GENERATED by scripts/gen-i18n-keys.mjs -- do not edit by hand.');
  L.push(' * Regenerate:  node scripts/generate-i18n-resources.mjs && node scripts/gen-i18n-keys.mjs');
  L.push(' * Report:      node scripts/report-i18n-counts.mjs  (key counts + coverage, same tree)');
  L.push(' *');
  L.push(' * ' + rows.length + ' keys; project-local additions: ' + localCount + '.');
  L.push(' */');
    // The leading-pipe form trips the ArkTS parser, so the first member
  // shares the declaration line.
  L.push("export type I18nKey = '" + rows[0].name + "'");
  rows.forEach((r, idx) => {
    if (idx === 0) {
      return;
    }
    const tail = idx === rows.length - 1 ? ';' : '';
    L.push("  | '" + r.name + "'" + tail);
  });
  L.push('');
  L.push('const ALL_KEYS: string[] = [');
  rows.forEach((r) => L.push("  '" + r.name + "',"));
  L.push('];');
  L.push('');
  L.push('const KEY_SET: Set<string> = new Set<string>(ALL_KEYS);');
  L.push('');
  L.push('/** Runtime guard for keys that arrive as plain strings. */');
  L.push('export function isI18nKey(value: string): boolean {');
  L.push('  return KEY_SET.has(value);');
  L.push('}');
  L.push('');
  L.push('/** Total number of known keys; scripts/report-i18n-counts.mjs reports the same number. */');
  L.push('export const I18N_KEY_COUNT: number = ' + rows.length + ';');
  L.push('');
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, L.join('\n'), 'utf8');
  return { out: OUT, keys: rows.length, localAdditions: localCount };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(url.fileURLToPath(import.meta.url));
if (isMain) {
  console.log(JSON.stringify(generateKeysSource(), null, 2));
}
